text = "the cat sat on the mat. the cat ate the rat. the rat sat on the hat. the hat sat on the cat."
ids = list(text.encode("utf-8"))

print("characters:", len(text))
print("tokens at start:", len(ids))
print("first 12 ids:", ids[:12])

from collections import Counter

def count_pairs(ids):
    return Counter(zip(ids, ids[1:])) # zip:- create pairs of 2 adjacent ids of all tokens list

# merge the repetitive characters into one common id
def merge(ids, pair, new_id):
    out, i = [], 0
    while i < len(ids):
        if i < len(ids) - 1 and (ids[i], ids[i+1]) == pair:
            out.append(new_id)          # glue the pair into one new token
            i += 2                      # skip BOTH old tokens
        else:
            out.append(ids[i])
            i += 1
    return out

vocab  = {i: bytes([i]) for i in range(256)}   # the 256 starting bytes
print(vocab) # byte code given to all numbers from 0 to 255
merges = {}

for k in range(10):

    print("\n")

    pair, freq = max(count_pairs(ids).items(), key=lambda x: x[1])    # most common pair
    print("pair, frequency:", count_pairs(ids).items())

    new_id = 256 + k  #256, 257, 258, ....                            # the next free id
    ids = merge(ids, pair, new_id)
    print("all ids with the now merged ones in sequence: ", ids)

    merges[pair] = new_id
    print("id of pair that is merged: ", merges)

    vocab[new_id] = vocab[pair[0]] + vocab[pair[1]]                   # remember its text and add it in vocabulary
    print(f"merge {k+1}: {vocab[new_id].decode()!r:12} seen {freq}x   tokens now {len(ids)}")

